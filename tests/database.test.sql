do $$
declare history public.money_activity%rowtype;
begin
    if (select balance from public.money_accounts where id = 1) <> 80
       or (select balance from public.money_accounts where id = 2) <> -20
       or (select balance from public.money_accounts where id = 3) <> 50 then
        raise exception 'transfer updated incorrect balances';
    end if;
    select * into strict history from public.money_activity where kind = 'transfer';
    if history.amount <> 20
       or history.accounts->0->>'role' <> 'source'
       or (history.accounts->0->>'before')::numeric <> 100
       or (history.accounts->0->>'after')::numeric <> 80
       or history.accounts->1->>'role' <> 'destination'
       or (history.accounts->1->>'before')::numeric <> -40
       or (history.accounts->1->>'after')::numeric <> -20 then
        raise exception 'incorrect transfer history: %', history.accounts;
    end if;
end $$;

