do $$
begin
    if not exists (select from pg_roles where rolname = 'anon') then create role anon; end if;
    if not exists (select from pg_roles where rolname = 'authenticated') then create role authenticated; end if;
end $$;
create schema auth;
create table auth.users (id uuid primary key);
create function auth.uid() returns uuid language sql stable
    as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
grant usage on schema auth to authenticated;
grant execute on function auth.uid() to authenticated;

create table public.money_accounts (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users,
    name text not null,
    type text not null,
    balance numeric(12,2)
);
create table public.money_transactions (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users,
    account_id bigint references public.money_accounts,
    description text not null,
    amount numeric(12,2),
    category text,
    transaction_date date
);
alter table public.money_accounts enable row level security;
alter table public.money_transactions enable row level security;
create policy own_accounts on public.money_accounts to authenticated
    using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy own_transactions on public.money_transactions to authenticated
    using (user_id = auth.uid()) with check (user_id = auth.uid());
grant select, insert, update, delete on public.money_accounts, public.money_transactions to authenticated;
grant usage on sequence public.money_transactions_id_seq to authenticated;

